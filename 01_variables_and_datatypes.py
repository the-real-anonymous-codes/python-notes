# ---------------- Numeric Types ----------------

a = 23
b = -12
c = 629
print(type(a))
print(type(b))
print(type(c))
print("To check the type of a variable we use type()")

x = 133.323
y = 233.4332
z = -24244 / 13412
v = 1232 / 1232
print(x)
print(y)
print(z)
print(v)
